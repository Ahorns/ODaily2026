def system_page(year: int, month: int, days: list[dict], projects: dict) -> str:
    mine = [d for d in days if d["date"].year == year and d["date"].month == month]
    hours = sum(d["hours"] for d in mine)
    label = f"{MONTHS[month - 1]} {year}"

    out = [
        "---",
        f"title: {yaml_str(label)}",
        'subtitle: "Stellar system"',
        "---",
        "",
        GENERATED_BANNER,
        "",
        f'<div class="stat-row">'
        f'<div class="stat"><span class="stat-value">{len(mine)}</span>'
        f'<span class="stat-label">planets</span></div>'
        f'<div class="stat"><span class="stat-value">{fmt_hours(hours) if hours else "0h"}</span>'
        f'<span class="stat-label">time logged</span></div>'
        f"</div>\n",
        "| Day | Time | Constellations |",
        "|:--|--:|:--|",
    ]
    for day in mine:
        iso = day["date"].isoformat()
        names = ", ".join(
            projects[s].get("name", s) for s in sorted({x["project"] for x in day["sessions"]})
        )
        marks = (" ✦" if day["milestone"] else "") + (" ☄" if day["idea"] else "")
        out.append(f"| [{day['date'].strftime('%a %d')}](../log/{iso}.qmd){marks} "
                   f"| {fmt_hours(day['hours'])} | {names or '—'} |")
    if not mine:
        out.append("| — | — | — |")
    out.append("")
    out.append("[← the whole galaxy](../index.qmd)")
    return "\n".join(out) + "\n"


def galaxy_page(year: int, days: list[dict]) -> str:
    mine = [d for d in days if d["date"].year == year]
    by_month: dict[int, list[dict]] = defaultdict(list)
    for day in mine:
        by_month[day["date"].month].append(day)

    out = [
        "---",
        f'title: "{year}"',
        'subtitle: "Galaxy"',
        "---",
        "",
        GENERATED_BANNER,
        "",
        f'<div class="stat-row">'
        f'<div class="stat"><span class="stat-value">{len(mine)}</span>'
        f'<span class="stat-label">days logged</span></div>'
        f'<div class="stat"><span class="stat-value">{fmt_hours(sum(d["hours"] for d in mine))}</span>'
        f'<span class="stat-label">time logged</span></div>'
        f'<div class="stat"><span class="stat-value">{len(by_month)}</span>'
        f'<span class="stat-label">systems</span></div>'
        f"</div>\n",
        "| System | Days | Time |",
        "|:--|--:|--:|",
    ]
    for month in sorted(by_month):
        group = by_month[month]
        out.append(f"| [{MONTHS[month - 1]}](../system/{year}-{month:02d}.qmd) "
                   f"| {len(group)} | {fmt_hours(sum(d['hours'] for d in group))} |")
    return "\n".join(out) + "\n"


def sky_page(group_key: str, group: dict, projects: dict, days: list[dict]) -> str:
    members = [s for s in projects if projects[s].get("group") == group_key]
    hours: dict[str, float] = defaultdict(float)
    seen: dict[str, set] = defaultdict(set)
    for day in days:
        for session in day["sessions"]:
            if session["project"] in members:
                hours[session["project"]] += session["hours"]
                seen[session["project"]].add(day["date"])

    total = sum(hours.values())
    covered = set().union(*seen.values()) if seen else set()

    out = [
        "---",
        f"title: {yaml_str(group.get('name', group_key))}",
        'subtitle: "Constellation family"',
        "---",
        "",
        GENERATED_BANNER,
        "",
    ]
    if group.get("blurb"):
        out.append(group["blurb"] + "\n")
    out.append(
        f'<div class="stat-row">'
        f'<div class="stat"><span class="stat-value">{fmt_hours(total) if total else "0h"}</span>'
        f'<span class="stat-label">total time</span></div>'
        f'<div class="stat"><span class="stat-value">{len(covered)}</span>'
        f'<span class="stat-label">days touched</span></div>'
        f'<div class="stat"><span class="stat-value">{len(members)}</span>'
        f'<span class="stat-label">constellations</span></div>'
        f"</div>\n"
    )
    out.append("| Constellation | Time | Days | Status |")
    out.append("|:--|--:|--:|:--|")
    for slug in sorted(members, key=lambda s: (-hours[s], s)):
        meta = projects[slug]
        out.append(f"| [{meta.get('name', slug)}](../projects/{slug}.qmd) "
                   f"| {fmt_hours(hours[slug]) if hours[slug] else '—'} "
                   f"| {len(seen[slug]) or '—'} | {meta.get('status', '—')} |")
    return "\n".join(out) + "\n"


def comets_page(days: list[dict]) -> str:
    """Ideas are comets: they arrive on their own schedule and are gone by
    morning unless written down. This is the page that makes writing them pay."""
    with_ideas = [d for d in days if d["idea_text"]]
    out = [
        "---",
        'title: "Comets"',
        'subtitle: "Every idea that came up, and the day it passed through."',
        "---",
        "",
        GENERATED_BANNER,
        "",
    ]
    if not with_ideas:
        out.append("_No ideas recorded yet. Write anything under "
                   "**An idea that came up** in a day's entry and it appears here._")
        return "\n".join(out) + "\n"

    out.append(
        f'<div class="stat-row">'
        f'<div class="stat"><span class="stat-value">{len(with_ideas)}</span>'
        f'<span class="stat-label">comets logged</span></div>'
        f'<div class="stat"><span class="stat-value">'
        f'{round(100 * len(with_ideas) / max(1, len(days)))}%</span>'
        f'<span class="stat-label">of days had one</span></div>'
        f"</div>\n"
    )
    for day in reversed(with_ideas):
        iso = day["date"].isoformat()
        out.append(f"### [{day['title']}](log/{iso}.qmd)\n")
        out.append(day["idea_text"] + "\n")
    return "\n".join(out) + "\n"


