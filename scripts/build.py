def fmt_hours(h: float) -> str:
    total = int(round(h * 60))
    hours, mins = divmod(total, 60)
    if hours and mins:
        return f"{hours}h {mins:02d}m"
    if hours:
        return f"{hours}h"
    return f"{mins}m"


def yaml_str(value) -> str:
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def seed_for(day: date) -> int:
    """Must match the seed the map computes, or an entry's planet would not be
    the one the map showed."""
    return day.year * 10000 + day.month * 100 + day.day


def sky_name(day: date) -> str:
    # Spread by a prime so consecutive days never land on neighbouring names.
    return SKY_NAMES[(seed_for(day) * 7919) % len(SKY_NAMES)]


def hex_to_rgb(value: str) -> tuple[float, float, float]:
    value = value.lstrip("#")
    return tuple(int(value[i:i + 2], 16) for i in (0, 2, 4))


def blend_colors(weighted: list[tuple[str, float]]) -> str:
    """Mix project colours in proportion to hours.

    Averaged in linear light rather than straight sRGB: mixing #ff0000 and
    #00ff00 the naive way gives a muddy olive, which would make every split day
    look like the same brown."""
    if not weighted:
        return "#7d8aa8"
    total = sum(w for _, w in weighted) or float(len(weighted))
    r = g = b = 0.0
    for colour, weight in weighted:
        share = (weight / total) if total else 1 / len(weighted)
        cr, cg, cb = hex_to_rgb(colour)
        r += (cr / 255) ** 2.2 * share
        g += (cg / 255) ** 2.2 * share
        b += (cb / 255) ** 2.2 * share
    out = [round(255 * max(0.0, min(1.0, c)) ** (1 / 2.2)) for c in (r, g, b)]
    return "#%02x%02x%02x" % tuple(out)


def day_color(day: dict, projects: dict) -> str:
    per: dict[str, float] = defaultdict(float)
    for session in day["sessions"]:
        per[session["project"]] += session["hours"]
    # A day with an entry but no hours still has projects; weight them equally.
    if per and not any(per.values()):
        per = {slug: 1.0 for slug in per}
    return blend_colors([(projects[s]["color"], h) for s, h in per.items()])


