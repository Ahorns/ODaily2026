def set_key(fm_lines: list[str], key: str, value: str) -> bool:
    """Replace or append a top-level scalar key. Nested session lines are
    indented, so matching on a column-zero key never touches them."""
    line = f"{key}: {value}"
    pattern = re.compile(rf"^{re.escape(key)}\s*:")
    for i, existing in enumerate(fm_lines):
        if pattern.match(existing):
            if existing.rstrip() == line:
                return False
            fm_lines[i] = line
            return True
    fm_lines.append(line)
    return True


def replace_region(body: str, begin: str, end: str, block: str) -> tuple[str, bool]:
    if begin not in body or end not in body:
        return body, False
    new = re.sub(
        re.escape(begin) + r".*?" + re.escape(end),
        lambda _: f"{begin}\n{block}\n{end}",
        body, flags=re.DOTALL,
    )
    return new, new != body


def time_table(day: dict, projects: dict, prefix: str = "../") -> str:
    if not day["sessions"]:
        return "_No time logged for this day._"

    per_project: dict[str, float] = defaultdict(float)
    notes: list[tuple[str, str]] = []
    for session in day["sessions"]:
        per_project[session["project"]] += session["hours"]
        if session.get("note"):
            notes.append((session["project"], str(session["note"])))

    rows = ["| Constellation | Kind | Time |", "|:--|:--|--:|"]
    for slug, hours in sorted(per_project.items(), key=lambda kv: (-kv[1], kv[0])):
        kinds = sorted({s["category"] for s in day["sessions"] if s["project"] == slug})
        name = projects[slug].get("name", slug)
        rows.append(f"| [{name}]({prefix}projects/{slug}.qmd) | {', '.join(kinds)} | {fmt_hours(hours)} |")
    rows.append(f"| **Total** | | **{fmt_hours(day['hours'])}** |")

    out = "\n".join(rows)
    if notes:
        out += "\n\n" + "\n".join(
            f"- **{projects[slug].get('name', slug)}** — {note}" for slug, note in notes
        )
    return out


def planet_name_for(day: dict) -> str:
    """A day's own `planet_name:` wins; otherwise the seeded catalogue name."""
    return day["fm"].get("planet_name") or sky_name(day["date"])


def planet_color_for(day: dict, projects: dict) -> str:
    """A day's own `planet_color:` wins; otherwise the projects' blend."""
    return day["fm"].get("planet_color") or day_color(day, projects)


def planet_orbit_au_for(day: dict) -> float | None:
    """A day's own `planet_orbit_au:` — a real (or invented) distance from its
    system's star, in whatever unit that system uses. None if the day is an
    ordinary logged day rather than a named body."""
    v = day["fm"].get("planet_orbit_au")
    return float(v) if v is not None else None


def planet_block(day: dict, projects: dict) -> str:
    # Sorted the same way the map sorts them, so a day's moons are the same
    # projects in the same order in both places.
    slugs = sorted({s["project"] for s in day["sessions"]})
    moon_colors = [projects[s]["color"] for s in slugs[1:]]
    name = planet_name_for(day)
    color = planet_color_for(day, projects)
    return (
        '<canvas class="day-planet" width="112" height="112" role="img" '
        f'aria-label="The planet for {day["date"].isoformat()}" '
        f'data-seed="{seed_for(day["date"])}" '
        f'data-type="{dominant_type(day)}" '
        f'data-color="{color}" '
        f'data-moons="{len(moon_colors)}" '
        f'data-moon-colors="{",".join(moon_colors)}" '
        f'data-milestone="{str(day["milestone"]).lower()}" '
        f'data-idea="{str(day["idea"]).lower()}"></canvas>\n'
        f'<p class="day-name">{name}</p>'
    )


def hydrate_day(day: dict, projects: dict) -> bool:
    fm_lines = day["fm_text"].split("\n")
    changed = False
    categories = sorted({s["project"] for s in day["sessions"]})

    changed |= set_key(fm_lines, "system", yaml_str(day["date"].strftime("%Y-%m")))
    changed |= set_key(fm_lines, "hours", str(day["hours"]))
    changed |= set_key(fm_lines, "categories", "[" + ", ".join(categories) + "]")

    body = day["body"]
    body, hit = replace_region(body, TIME_BEGIN, TIME_END, time_table(day, projects))
    changed |= hit
    if TIME_BEGIN not in day["body"]:
        print(f"  ! {day['path'].name}: no odaily:time markers, time table not written")

    body, hit = replace_region(body, PLANET_BEGIN, PLANET_END, planet_block(day, projects))
    changed |= hit
    if PLANET_BEGIN not in day["body"]:
        print(f"  ! {day['path'].name}: no odaily:planet markers, sprite not written")

    if changed:
        day["path"].write_text(
            "---\n" + "\n".join(fm_lines) + "\n---\n" + body, encoding="utf-8"
        )
    return changed


