"""Build the derived half of the site from the day entries.

Day files under `log/` are the only thing written by hand. Everything else — the
sky data the month map is drawn from, the constellation pages, the time tables,
the running totals — is regenerated from their frontmatter by this script. Run it
before `quarto render`:

    python scripts/build.py

It also hydrates regions it owns inside each day file: a few frontmatter keys,
the planet element at the top, and the time table between the `odaily:time`
markers. Everything else in the file is left exactly as written.
"""

