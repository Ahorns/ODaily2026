def load_registry() -> tuple[dict, dict]:
    data = yaml.safe_load((ROOT / "projects.yml").read_text(encoding="utf-8")) or {}
    projects = data.get("projects") or {}
    groups = data.get("groups") or {}
    for i, (slug, meta) in enumerate(sorted(projects.items())):
        colour = str(meta.get("color") or "").strip()
        if not re.fullmatch(r"#[0-9a-fA-F]{6}", colour):
            if colour:
                raise BuildError(
                    f"projects.yml: project '{slug}' has colour '{colour}' — "
                    f"use a six-digit hex like \"#4fc3f7\""
                )
            colour = HOUSE_COLORS[i % len(HOUSE_COLORS)]
        meta["color"] = colour.lower()
    for slug, meta in projects.items():
        group = meta.get("group")
        if group and group not in groups:
            raise BuildError(f"projects.yml: project '{slug}' is in unknown group '{group}'")
        category = meta.get("category")
        if category and category not in CATEGORY_TYPE:
            raise BuildError(
                f"projects.yml: project '{slug}' has unknown category '{category}' "
                f"— use one of {', '.join(CATEGORY_TYPE)}"
            )
    return projects, groups


def split_frontmatter(text: str) -> tuple[str, dict, str]:
    match = FM_RE.match(text)
    if not match:
        raise BuildError("file has no YAML frontmatter block")
    return match.group(1), yaml.safe_load(match.group(1)) or {}, text[match.end():]


def idea_text(body: str) -> str:
    """Whatever was written under the idea heading, comments stripped out."""
    match = re.search(
        rf"^##\s+{re.escape(IDEA_HEADING)}\s*$(.*?)(?=^##\s|\Z)",
        body, re.MULTILINE | re.DOTALL,
    )
    if not match:
        return ""
    text = re.sub(r"<!--.*?-->", "", match.group(1), flags=re.DOTALL)
    text = re.sub(r"^:::.*$", "", text, flags=re.MULTILINE)
    return " ".join(text.split())


def has_idea(body: str) -> bool:
    return bool(idea_text(body))


def read_days(projects: dict) -> list[dict]:
    days, problems = [], []
    for path in sorted(LOG_DIR.glob("*.qmd")):
        if path.name.startswith("_"):
            continue
        try:
            fm_text, fm, body = split_frontmatter(path.read_text(encoding="utf-8"))
        except BuildError as exc:
            problems.append(f"{path.name}: {exc}")
            continue

        try:
            day = date.fromisoformat(path.stem)
        except ValueError:
            problems.append(f"{path.name}: filename must be an ISO date, e.g. 2026-07-31.qmd")
            continue

        declared = fm.get("date")
        if isinstance(declared, date) and declared != day:
            problems.append(f"{path.name}: frontmatter date {declared} does not match the filename")

        sessions = fm.get("sessions") or []
        if not isinstance(sessions, list):
            problems.append(f"{path.name}: `sessions` must be a list")
            sessions = []

        clean = []
        for i, session in enumerate(sessions, 1):
            if not isinstance(session, dict):
                problems.append(f"{path.name}: session {i} must be a mapping")
                continue
            slug = session.get("project")
            if slug not in projects:
                problems.append(
                    f"{path.name}: session {i} refers to unknown project '{slug}' "
                    f"— add it to projects.yml"
                )
                continue
            try:
                hours = float(session.get("hours", 0) or 0)
            except (TypeError, ValueError):
                problems.append(f"{path.name}: session {i} has non-numeric hours")
                continue
            if hours < 0:
                problems.append(f"{path.name}: session {i} has negative hours")
                continue
            category = session.get("category") or projects[slug].get("category") or "admin"
            if category not in CATEGORY_TYPE:
                problems.append(
                    f"{path.name}: session {i} has unknown category '{category}' "
                    f"— use one of {', '.join(CATEGORY_TYPE)}"
                )
                continue
            clean.append({
                "project": slug, "hours": hours,
                "note": session.get("note"), "category": category,
            })

        days.append({
            "path": path,
            "date": day,
            "fm_text": fm_text,
            "fm": fm,
            "body": body,
            "sessions": clean,
            "hours": round(sum(s["hours"] for s in clean), 2),
            "demo": bool(fm.get("demo")),
            "milestone": bool(fm.get("milestone")),
            "idea": has_idea(body),
            "idea_text": idea_text(body),
            "title": fm.get("title") or day.isoformat(),
        })

    if problems:
        raise BuildError("\n".join("  - " + p for p in problems))
    return days


def dominant_type(day: dict) -> str:
    """The surface is whichever kind of work took the most of the day."""
    tally: dict[str, float] = defaultdict(float)
    for session in day["sessions"]:
        tally[session["category"]] += session["hours"]
    if not tally:
        return "rock"
    # Ties break alphabetically so the sprite never flickers between builds.
    best = max(sorted(tally), key=lambda c: tally[c])
    return CATEGORY_TYPE[best]


