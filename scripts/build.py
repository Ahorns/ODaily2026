def main() -> int:
    try:
        projects, groups = load_registry()
        LOG_DIR.mkdir(exist_ok=True)
        days = read_days(projects)
    except BuildError as exc:
        print("Build failed:\n" + str(exc), file=sys.stderr)
        return 1

    days.sort(key=lambda d: d["date"])
    print(f"Read {len(days)} day entries, {len(projects)} projects.")

    touched = sum(hydrate_day(day, projects) for day in days)
    print(f"Day files: {touched} hydrated.")

    write_if_changed(ASSET_DIR / "sky.json", sky_data(days, projects, groups))
    write_if_changed(INCLUDE_DIR / "summary.md", summary_include(days, date.today()))
    write_if_changed(INCLUDE_DIR / "archive.md", archive_include(days))
    write_if_changed(INCLUDE_DIR / "list.md", list_include(days, projects))

    if PROJECT_DIR.exists():
        shutil.rmtree(PROJECT_DIR)
    for slug, meta in projects.items():
        write_if_changed(PROJECT_DIR / f"{slug}.qmd", project_page(slug, meta, groups, days))
    write_if_changed(PROJECT_DIR / "index.qmd", projects_index(projects, groups, days))
    print(f"Constellations: {len(projects)} pages written.")

    # The same days along their other axes.
    for directory in (SYSTEM_DIR, SKY_DIR, YEAR_DIR):
        if directory.exists():
            shutil.rmtree(directory)

    months = sorted({(d["date"].year, d["date"].month) for d in days})
    for year, month in months:
        write_if_changed(SYSTEM_DIR / f"{year}-{month:02d}.qmd",
                         system_page(year, month, days, projects))
    for year in sorted({d["date"].year for d in days}):
        write_if_changed(YEAR_DIR / f"{year}.qmd", galaxy_page(year, days))
    for group_key, group in groups.items():
        write_if_changed(SKY_DIR / f"{group_key}.qmd", sky_page(group_key, group, projects, days))
    write_if_changed(ROOT / "comets.qmd", comets_page(days))
    print(f"Systems: {len(months)}, families: {len(groups)}, comets: "
          f"{sum(1 for d in days if d['idea_text'])}.")

    total = sum(d["hours"] for d in days)
    print(f"Total logged: {fmt_hours(total) if total else '0h'}, streak {streak(days, date.today())}.")

    # Loud on purpose: sample days inflate every total on the site, and they are
    # easy to forget about once the galaxy looks nicely full.
    demo = [d for d in days if d["demo"]]
    if demo:
        print(f"\n  NOTE: {len(demo)} of those {len(days)} days are sample data.")
        print("  Remove them with: python scripts/demo.py --clear")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
