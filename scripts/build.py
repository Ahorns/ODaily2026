def write_if_changed(path: Path, content: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    path.write_text(content, encoding="utf-8")
    return True


def sky_data(days: list[dict], projects: dict, groups: dict) -> str:
    """Everything the map needs, newest system first."""
    systems: dict[str, dict] = {}
    for day in days:
        rng = system_for(day["date"])
        system = systems.setdefault(rng["key"], {
            "key": rng["key"],
            "name": rng["name"],
            "start": rng["start"],
            "end": rng["end"],
            "days": {},
        })
        system["days"][day["date"].isoformat()] = {
            "hours": round(day["hours"], 2),
            "type": dominant_type(day),
            "color": planet_color_for(day, projects),
            "name": planet_name_for(day),
            "orbitAu": planet_orbit_au_for(day),
            "projects": sorted({s["project"] for s in day["sessions"]}),
            "milestone": day["milestone"],
            "idea": day["idea"],
            "title": day["title"],
            "url": f"log/{day['date'].isoformat()}.html",
            "sessions": [
                [projects[s["project"]].get("name", s["project"]), s["hours"], s.get("note") or ""]
                for s in day["sessions"]
            ],
        }

    # A day with a real `planet_orbit_au` sits at its own distance from the
    # sun rather than on the ring its calendar week happens to land on — that
    # is what makes Mercury sit near the sun and Eris sit at the outer edge
    # regardless of which week either falls in. Distances are compressed with
    # log10 (Eris is 170x further out than Mercury) and normalised against
    # only the other named bodies in the *same* system, so every system's
    # bodies use the full width of the ring band no matter its own scale.
    for system in systems.values():
        aus = [d["orbitAu"] for d in system["days"].values() if d["orbitAu"] is not None]
        if not aus:
            continue
        logs = [math.log10(au) for au in aus]
        lo, hi = min(logs), max(logs)
        for d in system["days"].values():
            if d["orbitAu"] is None:
                d["orbit"] = None
            elif hi == lo:
                d["orbit"] = 0.5
            else:
                d["orbit"] = (math.log10(d["orbitAu"]) - lo) / (hi - lo)

    # What each constellation amounts to, so the map can introduce one without
    # fetching its page. Totals are derived here rather than in the browser
    # because the browser only ever sees the days, never the sessions' shape.
    tally: dict[str, dict] = {}
    for day in days:
        for session in day["sessions"]:
            slug = session["project"]
            item = tally.setdefault(slug, {"days": set(), "hours": 0.0})
            item["days"].add(day["date"])
            item["hours"] += session["hours"]

    return json.dumps({
        "projects": {
            slug: {
                "name": meta.get("name", slug),
                "group": groups.get(meta.get("group"), {}).get("name", ""),
                "color": meta["color"],
                "blurb": meta.get("blurb", ""),
                "category": meta.get("category", ""),
                "status": meta.get("status", ""),
                "url": f"projects/{slug}.html",
                "days": len(tally.get(slug, {}).get("days") or ()),
                "hours": round(tally.get(slug, {}).get("hours", 0.0), 2),
                "first": min(tally[slug]["days"]).isoformat() if slug in tally else "",
                "last": max(tally[slug]["days"]).isoformat() if slug in tally else "",
            }
            for slug, meta in projects.items()
        },
        "systems": [
            {**s, "start": s["start"].isoformat(), "end": s["end"].isoformat()}
            for s in sorted(systems.values(), key=lambda s: s["start"], reverse=True)
        ],
    }, indent=1)


def streak(days: list[dict], today: date) -> int:
    logged = {d["date"] for d in days}
    # A streak that ended yesterday still counts today until the day is over.
    cursor = today if today in logged else today - timedelta(days=1)
    count = 0
    while cursor in logged:
        count += 1
        cursor -= timedelta(days=1)
    return count


def summary_include(days: list[dict], today: date) -> str:
    total = sum(d["hours"] for d in days)
    return "\n".join([
        GENERATED_BANNER,
        "",
        '<div class="stat-row">',
        f'<div class="stat"><span class="stat-value">{len(days)}</span>'
        f'<span class="stat-label">planets charted</span></div>',
        f'<div class="stat"><span class="stat-value">{fmt_hours(total) if total else "0h"}</span>'
        f'<span class="stat-label">time logged</span></div>',
        f'<div class="stat"><span class="stat-value">{streak(days, today)}</span>'
        f'<span class="stat-label">day streak</span></div>',
        "</div>",
        "",
    ])


def archive_include(days: list[dict]) -> str:
    """A plain list of every entry. It is the fallback when the canvas cannot
    run, and it is what the site search actually indexes."""
    out = [GENERATED_BANNER, ""]
    by_system: dict[tuple[int, int], list[dict]] = defaultdict(list)
    for day in days:
        by_system[(day["date"].year, day["date"].month)].append(day)

    for (year, month), system_days in sorted(by_system.items(), reverse=True):
        hours = sum(d["hours"] for d in system_days)
        out.append(f"### [{MONTHS[month - 1]} {year}](system/{year}-{month:02d}.qmd)")
        out.append("")
        out.append(f"{len(system_days)} days · {fmt_hours(hours)} · "
                   f"[the {year} galaxy](galaxy/{year}.qmd)")
        out.append("")
        for day in sorted(system_days, key=lambda d: d["date"], reverse=True):
            iso = day["date"].isoformat()
            marks = ("  ✦" if day["milestone"] else "") + ("  ☄" if day["idea"] else "")
            out.append(f"- [{day['title']}](log/{iso}.qmd) — {fmt_hours(day['hours'])}{marks}")
        out.append("")
    return "\n".join(out) + "\n"


def list_include(days: list[dict], projects: dict) -> str:
    """The other view of the same collection.

    A universe is for browsing and thinking; this is for finding what you did on
    12 March. The failure mode of a metaphor site is being delightful for thirty
    seconds and useless for the daily task, and you are the daily user."""
    head = [
        GENERATED_BANNER,
        "",
        '<table class="log-table" id="log-table">',
        "<thead><tr>"
        '<th data-sort="date" aria-sort="descending">Date</th>'
        '<th data-sort="name">Name</th>'
        '<th data-sort="hours" class="num">Hours</th>'
        '<th data-sort="kind">Kind</th>'
        '<th data-sort="projects">Constellations</th>'
        '<th data-sort="marks">·</th>'
        "</tr></thead>",
        "<tbody>",
    ]
    rows = []
    for day in reversed(days):
        iso = day["date"].isoformat()
        kinds = ", ".join(sorted({s["category"] for s in day["sessions"]})) or "—"
        slugs = sorted({s["project"] for s in day["sessions"]})
        names = ", ".join(projects[s].get("name", s) for s in slugs) or "—"
        swatches = "".join(
            f'<i class="swatch" style="background:{projects[s]["color"]}"></i>' for s in slugs
        )
        marks = ("✦" if day["milestone"] else "") + ("☄" if day["idea"] else "")
        rows.append(
            f'<tr data-date="{iso}" data-hours="{day["hours"]}">'
            f'<td><a href="log/{iso}.html">{iso}</a></td>'
            f'<td class="dim">{sky_name(day["date"])}</td>'
            f'<td class="num">{fmt_hours(day["hours"]) if day["hours"] else "—"}</td>'
            f"<td>{kinds}</td>"
            f'<td>{swatches}{names}</td>'
            f'<td class="marks">{marks or ""}</td>'
            f"</tr>"
        )
    if not rows:
        rows.append('<tr><td colspan="6" class="dim">Nothing logged yet.</td></tr>')
    return "\n".join(head + rows + ["</tbody>", "</table>", ""]) + "\n"


def project_page(slug: str, meta: dict, groups: dict, days: list[dict]) -> str:
    mine = [d for d in days if any(s["project"] == slug for s in d["sessions"])]
    hours = sum(s["hours"] for d in mine for s in d["sessions"] if s["project"] == slug)
    group = groups.get(meta.get("group"), {})

    out = [
        "---",
        f"title: {yaml_str(meta.get('name', slug))}",
        f"subtitle: {yaml_str('Constellation in ' + group.get('name', 'the field'))}",
        "---",
        "",
        GENERATED_BANNER,
        "",
    ]
    if meta.get("blurb"):
        out.append(f"{meta['blurb']}\n")

    if not mine:
        out.append("_No days logged against this constellation yet._")
        return "\n".join(out) + "\n"

    out.append(
        f'<div class="stat-row">'
        f'<div class="stat"><span class="stat-value">{fmt_hours(hours)}</span>'
        f'<span class="stat-label">total time</span></div>'
        f'<div class="stat"><span class="stat-value">{len(mine)}</span>'
        f'<span class="stat-label">days visited</span></div>'
        f'<div class="stat"><span class="stat-value">{mine[0]["date"].isoformat()}</span>'
        f'<span class="stat-label">first seen</span></div>'
        f"</div>\n"
    )
    out.append("| Day | Kind | Time | Note |")
    out.append("|:--|:--|--:|:--|")
    for day in reversed(mine):
        iso = day["date"].isoformat()
        mine_sessions = [s for s in day["sessions"] if s["project"] == slug]
        day_hours = sum(s["hours"] for s in mine_sessions)
        kinds = ", ".join(sorted({s["category"] for s in mine_sessions}))
        notes = " ".join(str(s["note"]) for s in mine_sessions if s.get("note"))
        out.append(f"| [{iso}](../log/{iso}.qmd) | {kinds} | {fmt_hours(day_hours)} | {notes or '—'} |")
    return "\n".join(out) + "\n"


def projects_index(projects: dict, groups: dict, days: list[dict]) -> str:
    hours: dict[str, float] = defaultdict(float)
    seen: dict[str, set] = defaultdict(set)
    for day in days:
        for session in day["sessions"]:
            hours[session["project"]] += session["hours"]
            seen[session["project"]].add(day["date"])

    out = [
        "---",
        'title: "Constellations"',
        'subtitle: "The same days, read along the other axis."',
        "---",
        "",
        GENERATED_BANNER,
        "",
        "A day is a planet and a month is a system, but a project is a *constellation*:",
        "a pattern drawn across whatever nights it happened to appear in. Pick one on the",
        "[galaxy](../index.qmd) map to see it traced across a month.",
        "",
    ]

    ungrouped = [s for s in projects if projects[s].get("group") not in groups]
    for group_key, group in list(groups.items()) + [(None, {"name": "Unfiled"})]:
        members = (
            ungrouped if group_key is None
            else [s for s in projects if projects[s].get("group") == group_key]
        )
        if not members:
            continue
        heading = group.get("name", group_key)
        out.append(f"## [{heading}](../sky/{group_key}.qmd)\n" if group_key else f"## {heading}\n")
        if group.get("blurb"):
            out.append(f"{group['blurb']}\n")
        out.append("| Constellation | Usually | Time | Days | Status |")
        out.append("|:--|:--|--:|--:|:--|")
        for slug in sorted(members, key=lambda s: (-hours[s], s)):
            meta = projects[slug]
            out.append(
                f"| [{meta.get('name', slug)}]({slug}.qmd) "
                f"| {meta.get('category', '—')} "
                f"| {fmt_hours(hours[slug]) if hours[slug] else '—'} "
                f"| {len(seen[slug]) or '—'} "
                f"| {meta.get('status', '—')} |"
            )
        out.append("")
    return "\n".join(out) + "\n"


